package org.prats.definitions;

public class PlatformECConfig {
    private String ecLabel;
    private String ecConfigPath;

    public String getEcLabel() {
        return ecLabel;
    }

    public void setEcLabel(String ecLabel) {
        this.ecLabel = ecLabel;
    }

    public String getEcConfigPath() {
        return ecConfigPath;
    }

    public void setEcConfigPath(String ecConfigPath) {
        this.ecConfigPath = ecConfigPath;
    }
}
